#!/usr/bin/env node
// Writes packages/core/src/idna-tables.ts: the stringprep tables nameprep
// uses (RFC 3454, on Unicode 3.2), packed by idna-tables.compose.ts from the
// RFC's text, which is committed beside it (idna-tables.rfc3454.txt, fetched
// from rfc-editor.org when missing). The Worker and the web UI share the
// tables through `@tstodon/core/post-text`.
// `packages/core/src/idna.test.ts` fails when the file is stale.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { composeIdnaTables } from "../packages/core/src/idna-tables.compose.ts";

const path = (name) => fileURLToPath(new URL(`../packages/core/src/${name}`, import.meta.url));
const rfc = path("idna-tables.rfc3454.txt");

if (!existsSync(rfc)) {
  const response = await fetch("https://www.rfc-editor.org/rfc/rfc3454.txt");
  if (!response.ok) {
    throw new Error(`rfc3454.txt: ${response.status}`);
  }
  writeFileSync(rfc, await response.text());
}

const target = path("idna-tables.ts");
writeFileSync(
  target,
  `// Generated by scripts/generate-idna-tables.mjs from RFC 3454. Do not edit.
/** Nameprep's tables, packed: see \`composeIdnaTables\`. */
export const IDNA_TABLES = {
${Object.entries(composeIdnaTables(readFileSync(rfc, "utf8")))
  .map(([name, packed]) => `  ${name}:\n    ${JSON.stringify(packed)},`)
  .join("\n")}
};
`,
);
console.log(`wrote ${target}`);
