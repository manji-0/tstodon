#!/usr/bin/env node
// Writes packages/core/src/languages.ts from Mastodon's
// `LanguagesHelper::SUPPORTED_LOCALES`, read by Ruby from a Mastodon
// checkout's `app/helpers/languages_helper.rb`:
//
//   node scripts/generate-languages.mjs ~/mastodon/app/helpers/languages_helper.rb
//
// Run it again when the vendored web app moves to a newer Mastodon release.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const [helper] = process.argv.slice(2);
if (helper === undefined) {
  console.error(
    "usage: node scripts/generate-languages.mjs <mastodon>/app/helpers/languages_helper.rb",
  );
  process.exit(1);
}

const locales = JSON.parse(
  execFileSync(
    "ruby",
    [
      "-rjson",
      "-e",
      "load ARGV[0]; puts JSON.generate(LanguagesHelper::SUPPORTED_LOCALES)",
      helper,
    ],
    { encoding: "utf8" },
  ),
);

const rows = Object.entries(locales)
  .map(
    ([code, [name, nativeName]]) =>
      `  [${[code, name, nativeName].map((s) => JSON.stringify(s)).join(", ")}],`,
  )
  .join("\n");

const target = fileURLToPath(new URL("../packages/core/src/languages.ts", import.meta.url));
writeFileSync(
  target,
  `// Generated by scripts/generate-languages.mjs from Mastodon's app/helpers/languages_helper.rb. Do not edit.

/**
 * Mastodon's \`LanguagesHelper::SUPPORTED_LOCALES\`, in its order (ISO 639-1,
 * their regional variants, ISO 639-3 and theirs): each code with its English
 * and its native name. \`GET /api/v1/instance/languages\` lists them, and the web
 * app's initial state carries them.
 */
export const Languages = [
${rows}
] as const satisfies ReadonlyArray<readonly [code: string, name: string, nativeName: string]>;

/** The codes of {@link Languages}, which \`LanguageValidator\` accepts (\`valid_locale?\`). */
export const SupportedLocales: ReadonlySet<string> = new Set(Languages.map(([code]) => code));
`,
);
