// The source of packages/worker/server/jsonld-contexts.ts, from what
// scripts/jsonld-reference.rb prints: `contexts` (URL to document) and
// `fullContext`. URLs that hold the same document (schema.org's aliases)
// share one copy in the module.

/** `contexts` as `[urls, document]`, one entry per distinct document, in first-seen order. */
const grouped = (contexts) => {
  const byDocument = new Map();
  for (const [url, document] of Object.entries(contexts)) {
    const key = JSON.stringify(document);
    const entry = byDocument.get(key);
    if (entry === undefined) {
      byDocument.set(key, [[url], document]);
    } else {
      entry[0].push(url);
    }
  }
  return [...byDocument.values()];
};

export const jsonldContextsModule = (image, contexts, fullContext) =>
  `// Generated by scripts/generate-jsonld-reference.mjs from ${image}; do not edit.
// The JSON-LD contexts Mastodon preloads, as its processor holds them.

/** Each document, with the URLs it is preloaded under. */
const DOCUMENTS: ReadonlyArray<
  readonly [ReadonlyArray<string>, Readonly<Record<string, unknown>>]
> = ${JSON.stringify(grouped(contexts))};

/**
 * Each context by its \`https://\` URL: Mastodon's own and those of the
 * \`json-ld-preloaded\` gem but three large ones (scripts/jsonld-reference.rb).
 * tstodon reads an \`http://\` URL as its \`https://\` one, and fetches any
 * other context (\`jsonld-remote-contexts.ts\`).
 */
export const JSONLD_CONTEXTS: ReadonlyMap<string, Readonly<Record<string, unknown>>> = new Map(
  DOCUMENTS.flatMap(([urls, document]) => urls.map((url) => [url, document] as const)),
);

/** \`ContextHelper#full_context\`: what Mastodon compacts a signed activity to before it reads it. */
export const MASTODON_FULL_CONTEXT: ReadonlyArray<unknown> = ${JSON.stringify(fullContext)};
`;
