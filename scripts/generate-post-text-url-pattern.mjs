#!/usr/bin/env node
// Writes packages/core/src/post-text-url-pattern.ts: the URL pattern Mastodon's
// web UI composed from twitter-text (`features/compose/util/url_regex.js`),
// frozen as a string so the Worker and the web UI share it without loading
// twitter-text (CommonJS, core-js polyfills) at run time.
// `packages/core/src/post-text.test.ts` fails when the file is stale.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { composePostUrlPattern } from "../packages/core/src/post-text-url-pattern.compose.ts";

const target = fileURLToPath(
  new URL("../packages/core/src/post-text-url-pattern.ts", import.meta.url),
);
const { source, flags } = composePostUrlPattern();

writeFileSync(
  target,
  `// Generated by scripts/generate-post-text-url-pattern.mjs from twitter-text. Do not edit.
export const POST_URL_PATTERN = {
  source:
    ${JSON.stringify(source)},
  flags: ${JSON.stringify(flags)},
} as const;
`,
);
console.log(`wrote ${target} (${source.length} characters)`);
