#!/usr/bin/env node
// Writes packages/core/src/post-text-url-pattern.ts: the URL patterns of
// Mastodon's server (`config/initializers/twitter_regex.rb` over the
// twitter-text gem), composed in post-text-url-pattern.compose.ts and frozen
// as strings so the Worker and the web UI share them without loading
// twitter-text (CommonJS, core-js polyfills) at run time. A source several
// patterns repeat (the top-level domains) is written once.
// `packages/core/src/post-text.test.ts` fails when the file is stale.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { composePostTextPatterns } from "../packages/core/src/post-text-url-pattern.compose.ts";

const target = fileURLToPath(
  new URL("../packages/core/src/post-text-url-pattern.ts", import.meta.url),
);
const { patterns, fragments } = composePostTextPatterns();

/** `source` as a string expression that names each of `names`' fragments where it holds one. */
const expression = (source, names) => {
  const [name, ...rest] = names;
  if (name === undefined) {
    return JSON.stringify(source);
  }
  return source
    .split(fragments[name])
    .map((part) => (part === "" ? [] : [expression(part, rest)]))
    .reduce((parts, part) => [...parts, name, ...part])
    .join(" + ");
};

writeFileSync(
  target,
  `// Generated by scripts/generate-post-text-url-pattern.mjs from twitter-text. Do not edit.
const TLD = ${expression(fragments.TLD, [])};
const URL_TAIL = ${expression(fragments.URL_TAIL, ["TLD"])};
/** Sources for the \`iu\` flags: see \`composePostTextPatterns\`. */
export const POST_TEXT_PATTERNS = {
${Object.entries(patterns)
  .map(([name, source]) => `  ${name}: ${expression(source, ["URL_TAIL", "TLD"])},`)
  .join("\n")}
};
`,
);
console.log(`wrote ${target}`);
